"""Module 1 Figure 1 entry point.

The formal Figure 1 asset was rebuilt in R051 as a source-audited, relative-only
figure. This compatibility wrapper keeps the historical module entry point while
preventing the older provisional absolute-OCR/Bayesian layout from being
regenerated by batch scripts.
"""

from __future__ import annotations

from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.publication_figures.main.figure1_neuron_comparison_verified import (
    generate,
)


def make_figure1() -> str:
    """Generate the R051 source-audited Figure 1 and return the PNG path."""
    png, _pdf = generate()
    print(f"Saved: {png}")
    return str(Path(png))


if __name__ == "__main__":
    make_figure1()
